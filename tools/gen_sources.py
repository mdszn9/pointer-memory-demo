#!/usr/bin/env python3
"""Regenerate sources.js from the real .c files in code/.

Run after editing any example:   python3 tools/gen_sources.py
This keeps the line numbers shown on the web page identical to the files
students compile, so a step that highlights "line 11" really is line 11.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = sorted((ROOT / "code").glob("0*.c"))

out = ["// GENERATED by tools/gen_sources.py -- do not edit by hand.",
       "// Source of truth: the .c files in code/",
       "const SOURCES = {"]
for path in SRC:
    text = path.read_text().rstrip("\n")
    out.append("  %s: %s," % (json.dumps(path.name), json.dumps(text)))
out.append("};")
(ROOT / "sources.js").write_text("\n".join(out) + "\n")
print("wrote sources.js from %d files" % len(SRC))
